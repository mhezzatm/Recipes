export const searchRecipesByName = async (name, pageNumber, size) => {
  let recipeList = [];

  const url = `https://tasty.p.rapidapi.com/recipes/list?from=${
    (pageNumber - 1) * size
  }&size=${size}&q=${name}`;
  const options = {
    method: "GET",
    headers: {
      "X-RapidAPI-Key": "6fe2cef339msh30d7a18b8ca5bdcp1f6234jsn3a1022079a5c",
      "X-RapidAPI-Host": "tasty.p.rapidapi.com",
    },
  };
  let result = "";

  try {
    const response = await fetch(url, options);
    result = await response.json();
    recipeList = await result.results;
    console.log(result);
  } catch (error) {
    console.error(error);
  }

  const recipes = [];

  recipeList.forEach((r) => {
    const recipe = {
      name: r.name,
      id: r.id,
      description: r.description,
      thumbnail_url: r.thumbnail_url,
      rate: r.user_ratings,
    };
    recipes.push(recipe);
  });

  return { recipes, count: result.count };
};
