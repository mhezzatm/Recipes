export const autoComplete = async (name) => {
  const url = "https://tasty.p.rapidapi.com/recipes/auto-complete?prefix=" + name;
  const options = {
    method: "GET",
    headers: {
      "X-RapidAPI-Key": "6fe2cef339msh30d7a18b8ca5bdcp1f6234jsn3a1022079a5c",
      "X-RapidAPI-Host": "tasty.p.rapidapi.com",
    },
  };
  const searchList = [];
  try {
    const response = await fetch(url, options);
    const result = await response.json();
    console.log(result);
    result.results.forEach((r) => {
      searchList.push(r.search_value);
    });
    return searchList;
  } catch (error) {
    console.error(error);
  }
};
